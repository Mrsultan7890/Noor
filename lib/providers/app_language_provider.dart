import 'package:flutter/widgets.dart';
import 'package:provider/provider.dart';
import 'package:shared_preferences/shared_preferences.dart';

class AppLanguageProvider extends ChangeNotifier {
  AppLanguageProvider._(this._language);

  static const languages = <AppLanguage>[
    AppLanguage(
      name: 'English',
      code: 'en',
      nativeName: 'English',
      quranEdition: 'en.sahih',
    ),
    AppLanguage(
      name: 'Urdu',
      code: 'ur',
      nativeName: 'اردو',
      quranEdition: 'ur.jalandhry',
    ),
    AppLanguage(
      name: 'Arabic',
      code: 'ar',
      nativeName: 'العربية',
      quranEdition: 'ar.muyassar',
    ),
    AppLanguage(
      name: 'Indonesian',
      code: 'id',
      nativeName: 'Bahasa Indonesia',
      quranEdition: 'id.indonesian',
    ),
    AppLanguage(
      name: 'Turkish',
      code: 'tr',
      nativeName: 'Türkçe',
      quranEdition: 'tr.diyanet',
    ),
    AppLanguage(
      name: 'French',
      code: 'fr',
      nativeName: 'Français',
      quranEdition: 'fr.hamidullah',
    ),
  ];

  static const _preferenceKey = 'selected_language';
  AppLanguage _language;

  AppLanguage get language => _language;
  String get languageName => _language.name;
  String get languageCode => _language.code;
  TextDirection get textDirection =>
      _language.code == 'ar' || _language.code == 'ur'
          ? TextDirection.rtl
          : TextDirection.ltr;

  static Future<AppLanguageProvider> load() async {
    final preferences = await SharedPreferences.getInstance();
    final savedName = preferences.getString(_preferenceKey);
    final language = languages.firstWhere(
      (item) => item.name == savedName,
      orElse: () => languages.first,
    );
    return AppLanguageProvider._(language);
  }

  Future<void> setLanguage(String name) async {
    final language = languages.firstWhere(
      (item) => item.name == name,
      orElse: () => throw ArgumentError.value(name, 'name', 'Unknown language'),
    );
    if (language == _language) return;
    final preferences = await SharedPreferences.getInstance();
    await preferences.setString(_preferenceKey, language.name);
    await preferences.setString('quran_edition', language.quranEdition);
    _language = language;
    notifyListeners();
  }

  String translate(String source) =>
      _translations[_language.code]?[source] ?? source;
}

class AppLanguage {
  const AppLanguage({
    required this.name,
    required this.code,
    required this.nativeName,
    required this.quranEdition,
  });

  final String name;
  final String code;
  final String nativeName;
  final String quranEdition;
}

extension AppLanguageBuildContext on BuildContext {
  String tr(String source) => watch<AppLanguageProvider>().translate(source);
}

